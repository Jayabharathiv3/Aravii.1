function getNormalizedRoute() {
    // Check hash first (e.g. #chat, #dashboard)
    const hash = window.location.hash.replace('#', '').trim();
    if (hash) {
        const cleanHash = hash.split('?')[0].replace(/^\//, '');
        if (cleanHash) return cleanHash;
    }

    // Check pathname (e.g. /chat, /dashboard)
    const path = window.location.pathname.replace(/^\//, '').split('?')[0];
    if (path && path !== 'index.html') {
        return path;
    }
    return 'dashboard';
}

function navigateTo(route) {
    // We update hash to ensure no 404 on refresh on any static host,
    // while keeping history state clean
    window.location.hash = `#${route}`;
    renderRoute(route);
}

// Global alert notification
function showAlert(message, type = 'info') {
    const container = document.getElementById('flashContainer');
    if (!container) return;
    const alertDiv = document.createElement('div');
    alertDiv.className = `alert alert-${type}`;
    alertDiv.innerHTML = `<span>${message}</span><button onclick="this.parentElement.remove()" style="background:none;border:none;cursor:pointer;font-weight:bold;">&times;</button>`;
    container.innerHTML = '';
    container.appendChild(alertDiv);
    setTimeout(() => {
        if (alertDiv.parentElement) alertDiv.remove();
    }, 6000);
}

