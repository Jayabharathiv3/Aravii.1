async function callGeminiText(prompt, businessContext) {
    const key = getActiveApiKey();
    if (!key) {
        throw new Error("Gemini API key is not configured. Click 'Configure API Key' in the top right to paste your free Google Gemini API key.");
    }

    let fullPrompt = prompt;
    if (businessContext && businessContext.businessName) {
        fullPrompt = `[Client Business Context: Company: ${businessContext.businessName}, Industry: ${businessContext.industry}, Budget: ${businessContext.budget}, Goals: ${businessContext.goals}, Target Customers: ${businessContext.targetCustomers}]\n\nClient Question:\n${prompt}`;
    }

    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${encodeURIComponent(key)}`;

    const requestBody = {
        contents: [
            {
                role: "user",
                parts: [{ text: fullPrompt }]
            }
        ],
        systemInstruction: {
            parts: [{ text: CONSULTANT_SYSTEM_PROMPT }]
        }
    };

    const res = await fetch(endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(requestBody)
    });

    if (!res.ok) {
        const errorData = await res.json().catch(() => ({}));
        const msg = errorData.error?.message || `HTTP ${res.status} error`;
        throw new Error(msg);
    }

    const data = await res.json();
    const replyText = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!replyText) {
        throw new Error("No response content generated by model.");
    }
    return replyText;
}

