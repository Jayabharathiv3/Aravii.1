function isRouteActive(r) {
    return getNormalizedRoute() === r;
}

function renderRoute(route) {
    const mainContainer = document.getElementById('mainContent');
    if (!mainContainer) return;

    // Check Authentication: unauthenticated users redirect to login
    if (!AppState.currentUser && route !== 'login' && route !== 'register') {
        route = 'login';
        window.location.hash = '#login';
    } else if (AppState.currentUser && (route === 'login' || route === 'register')) {
        route = 'dashboard';
        window.location.hash = '#dashboard';
    }

    renderNavbar();

    switch (route) {
        case 'login':
            renderLoginView(mainContainer);
            break;
        case 'register':
            renderRegisterView(mainContainer);
            break;
        case 'dashboard':
            renderDashboardView(mainContainer);
            break;
        case 'chat':
            renderChatView(mainContainer);
            break;
        case 'image-analysis':
            renderImageView(mainContainer);
            break;
        case 'profile':
            renderProfileView(mainContainer);
            break;
        default:
            renderDashboardView(mainContainer);
            break;
    }
}

